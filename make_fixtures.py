"""FASTKEYS Gate fixtures: synthesize known-reference audio cases.

Each fixture is generated by construction, so the reference (key, chords,
melody) is exact ground truth. No manual repair of model output allowed.

Case A (fixture_hymn_G.wav): clean keyboard-style melody, G major.
  Tune: "Amazing Grace" (public domain, NEW BRITAIN), first phrase.
  Melody (G major): G3 C4 E4 C4 E4 D4 C4 A3 G3 ...
  Reference key: G Major. Chord pad: G, C, G, D, G (one per bar).
Case B (fixture_lead_D.wav): melody-forward lead + accompaniment, D major.
  Lead plays "When I Survey" (Hamburg) first line melody; pad plays D/A/G.
  Tests polyphonic handling with a dominant lead line.
Case C (fixture_pop_C.wav): keyboardist pop progression C-G-Am-F with melody.
  Four-chord loop with a simple stepwise melody on top.

Synthesis: harmonic tone = sum of sine partials (1, 0.5, 0.25, 0.125)
with exponential decay envelope, 22050 Hz mono, matching pipeline input.
"""
import numpy as np
import soundfile as sf

SR = 22050

NOTE_NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B']


def midi_to_freq(m):
    return 440.0 * 2 ** ((m - 69) / 12)


def note_name(m):
    return f"{NOTE_NAMES[m % 12]}{(m // 12) - 1}"


def tone(midi, start, dur, gain=0.5, partials=(1.0, 0.4, 0.2, 0.1)):
    n = int(dur * SR)
    t = np.arange(n) / SR
    f = midi_to_freq(midi)
    sig = np.zeros(n)
    for k, a in enumerate(partials, start=1):
        sig += a * np.sin(2 * np.pi * f * k * t)
    # simple ADSR-ish envelope: 10ms attack, exp decay to 60%, 50ms release
    env = np.ones(n)
    atk = min(int(0.01 * SR), n)
    env[:atk] = np.linspace(0, 1, atk)
    rel = min(int(0.05 * SR), n)
    env[-rel:] *= np.linspace(1, 0, rel)
    env *= np.exp(-0.6 * t / max(dur, 0.01)) * 0.5 + 0.5
    return start, gain * env * sig


def render(events, total_dur):
    out = np.zeros(int(total_dur * SR))
    for start, sig in events:
        i = int(start * SR)
        j = min(len(out), i + len(sig))
        out[i:j] += sig[: j - i]
    out /= max(1e-9, np.abs(out).max())
    out *= 0.89
    return out


def N(name, octave):
    semis = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5,
             'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}
    return semis[name] + (octave + 1) * 12


