melody_a = [
    ('G', 3, 0.0, 0.6), ('C', 4, 0.6, 1.2), ('E', 4, 1.8, 1.2),
    ('C', 4, 3.0, 0.6), ('E', 4, 3.6, 1.2), ('D', 4, 4.8, 1.8),
    ('C', 4, 6.6, 0.6), ('A', 3, 7.2, 1.2), ('G', 3, 8.4, 1.8),
]
# pad: one chord per 3s bar: G, C, G, D
pad_a = [
    ([('G', 2), ('B', 2), ('D', 3)], 0.0, 3.0),
    ([('C', 3), ('E', 3), ('G', 3)], 3.0, 3.0),
    ([('G', 2), ('B', 2), ('D', 3)], 6.0, 2.4),
]
ev = []
for name, octv, st, du in melody_a:
    ev.append(tone(N(name, octv), st, du, gain=0.55))
for chord, st, du in pad_a:
    for name, octv in chord:
        ev.append(tone(N(name, octv), st, du, gain=0.12))
wav_a = render(ev, 10.2)
sf.write('fixture_hymn_G.wav', wav_a, SR)
print('wrote fixture_hymn_G.wav',
      [(note_name(N(n, o)), st) for n, o, st, _ in melody_a][:4], '...')

